import 'package:flutter/material.dart';

class PhraseThemeData {
  final Color backgroundColor;
  final Color foregroundColor;
  final Color dimTextColor;
  final Color translationColor;
  final Color activeAccentColor;
  final Color activeFillColor;
  final Color highlightBg;
  final Color cuNewColor;
  final Color clLearnColor;
  final Color ckKnownColor;

  const PhraseThemeData({
    required this.backgroundColor,
    required this.foregroundColor,
    required this.dimTextColor,
    required this.translationColor,
    required this.activeAccentColor,
    required this.activeFillColor,
    required this.highlightBg,
    required this.cuNewColor,
    required this.clLearnColor,
    required this.ckKnownColor,
  });
}
